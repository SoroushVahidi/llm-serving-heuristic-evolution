#!/usr/bin/env python3
"""Offline PARS scoring for (1) the real WildChat evaluation prompts and
(2) the canonical benchmark suite's accepted synthetic workloads.

**Why the canonical-suite path needs a text-matching step, and what it
does** (see docs/audits/pars_first_comparative_evaluation_20260804.md for
the full rationale): PARS is a text-based BERT scorer, but
`benchmarks/canonical_suite/<family>/seed_<n>.json` requests (generated by
`scripts/generate_canonical_benchmark_suite.py`) carry only integer
`prompt_tokens` counts -- no prompt text field exists at all (by design;
see that generator's own docstring). Inventing arbitrary placeholder text
of the right length would make PARS score meaningless lorem-ipsum content
rather than anything resembling a real prompt, which would silently
invalidate the whole comparison. Instead: every synthetic request is
matched to the REAL WildChat prompt whose token count (under PARS's own
`bert-base-uncased` tokenizer, not the `facebook/opt-125m` count already
recorded for WildChat) is closest to that request's `prompt_tokens`
target, and PARS scores that real matched text. This necessarily reuses
WildChat prompts many times over (900 requests per family across 3 seeds,
vs. only 300 distinct real prompts) -- quantified and reported explicitly,
not hidden, via each family's `matching_manifest.json`.

The synthetic Request's own `prompt_tokens`/timing/deadline/priority
fields, used by the SIMULATOR, are never altered by this script -- only
"what text does PARS see when scoring this request" is resolved this way.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Dict, List, Tuple

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from baselines.pars.adapter.checkpoint_loader import load_pars_predictor
from baselines.pars.adapter.offline_scoring import save_score_cache, score_prompts_offline

WILDCHAT_PROMPTS_PATH = "data/processed/wildchat/wildchat_eval_prompts_by_id.json"
CANONICAL_SUITE_DIR = "benchmarks/canonical_suite"
DEFAULT_OUTPUT_DIR = "results/pars_official"


def _load_wildchat_prompts() -> Dict[int, str]:
    with open(WILDCHAT_PROMPTS_PATH, "r", encoding="utf-8") as f:
        raw = json.load(f)
    return {int(k): v for k, v in raw.items()}


def _bert_token_counts(tokenizer, prompts_by_id: Dict[int, str]) -> Dict[int, int]:
    ids = list(prompts_by_id.keys())
    texts = [prompts_by_id[i] for i in ids]
    encoded = tokenizer(texts, truncation=False)["input_ids"]
    return {rid: len(toks) for rid, toks in zip(ids, encoded)}


def _match_synthetic_requests_to_real_text(
    synthetic_prompt_tokens: Dict[int, int],  # synthetic request_id -> target prompt_tokens
    wildchat_bert_lengths: Dict[int, int],    # wildchat request_id -> real bert token count
    wildchat_prompts: Dict[int, str],
) -> Tuple[Dict[int, str], Dict[int, dict]]:
    """Nearest-neighbor match (by absolute bert-token-count difference,
    ties broken by ascending wildchat_request_id for determinism). Returns
    (synthetic_request_id -> matched real prompt text,
     synthetic_request_id -> match metadata)."""
    sorted_wc = sorted(wildchat_bert_lengths.items(), key=lambda kv: (kv[1], kv[0]))
    lengths_only = [length for _rid, length in sorted_wc]

    def _nearest_index(target: int) -> int:
        # Binary search would be faster; linear scan is fine at 300 items.
        best_idx, best_diff = 0, abs(lengths_only[0] - target)
        for idx, length in enumerate(lengths_only):
            diff = abs(length - target)
            if diff < best_diff:
                best_idx, best_diff = idx, diff
        return best_idx

    matched_text: Dict[int, str] = {}
    match_meta: Dict[int, dict] = {}
    for req_id, target_len in synthetic_prompt_tokens.items():
        idx = _nearest_index(target_len)
        wc_rid, wc_len = sorted_wc[idx]
        matched_text[req_id] = wildchat_prompts[wc_rid]
        match_meta[req_id] = {
            "target_prompt_tokens": target_len,
            "matched_wildchat_request_id": wc_rid,
            "matched_wildchat_bert_token_count": wc_len,
            "abs_diff": abs(wc_len - target_len),
        }
    return matched_text, match_meta


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint-path", required=True)
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--families", nargs="+", default=None,
                         help="Canonical-suite family names to score (default: read from suite_manifest.json's 'accepted' list).")
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--skip-wildchat", action="store_true")
    parser.add_argument("--skip-canonical-suite", action="store_true")
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    handle = load_pars_predictor(args.checkpoint_path)
    print(f"Loaded PARS predictor from {args.checkpoint_path}")

    wildchat_prompts = _load_wildchat_prompts()

    if not args.skip_wildchat:
        wc_cache = score_prompts_offline(handle, wildchat_prompts, batch_size=args.batch_size)
        wc_path = os.path.join(args.output_dir, "wildchat_score_cache.json")
        save_score_cache(wc_cache, wc_path)
        print(f"Scored {len(wc_cache)} WildChat prompts -> {wc_path}")

    if args.skip_canonical_suite:
        return

    families = args.families
    if families is None:
        with open(os.path.join(CANONICAL_SUITE_DIR, "suite_manifest.json")) as f:
            families = json.load(f)["accepted"]

    # BERT token counts for the WildChat pool -- computed once, reused for
    # every family/seed's nearest-neighbor matching.
    wildchat_bert_lengths = _bert_token_counts(handle.tokenizer, wildchat_prompts)

    for family in families:
        family_dir = os.path.join(CANONICAL_SUITE_DIR, family)
        out_family_dir = os.path.join(args.output_dir, "canonical_suite_matched", family)
        os.makedirs(out_family_dir, exist_ok=True)
        for seed in args.seeds:
            dataset_path = os.path.join(family_dir, f"seed_{seed}.json")
            with open(dataset_path, "r", encoding="utf-8") as f:
                rows = json.load(f)
            synthetic_prompt_tokens = {r["request_id"]: r["prompt_tokens"] for r in rows}

            matched_text, match_meta = _match_synthetic_requests_to_real_text(
                synthetic_prompt_tokens, wildchat_bert_lengths, wildchat_prompts
            )
            cache = score_prompts_offline(handle, matched_text, batch_size=args.batch_size)

            scores_path = os.path.join(out_family_dir, f"seed_{seed}_score_cache.json")
            save_score_cache(cache, scores_path)

            n_distinct_wc_used = len({m["matched_wildchat_request_id"] for m in match_meta.values()})
            manifest = {
                "family": family,
                "seed": seed,
                "n_synthetic_requests": len(rows),
                "n_distinct_wildchat_prompts_used": n_distinct_wc_used,
                "mean_abs_token_match_diff": sum(m["abs_diff"] for m in match_meta.values()) / len(match_meta),
                "max_abs_token_match_diff": max(m["abs_diff"] for m in match_meta.values()),
                "match_detail": match_meta,
            }
            manifest_path = os.path.join(out_family_dir, f"seed_{seed}_matching_manifest.json")
            with open(manifest_path, "w", encoding="utf-8") as f:
                json.dump(manifest, f, indent=2)

            print(f"{family} seed={seed}: scored {len(cache)} requests "
                  f"(reused {n_distinct_wc_used}/300 distinct WildChat prompts, "
                  f"mean|diff|={manifest['mean_abs_token_match_diff']:.1f} tokens) -> {scores_path}")


if __name__ == "__main__":
    main()
