# ---------------------------------------------------------------------------
# Ordering entropy (new metric, not in the prior audit's checker): Shannon
# entropy (bits) of the SRTF-rank of the request FIFO actually admits
# first at each nonempty, contended (queue_size>=2) decision. Low entropy
# (peaked near rank 0) means FIFO's arrival order already tracks SRTF's
# preference most of the time -- little to gain from reordering. High
# entropy (spread across ranks) means arrival order and service-time order
# are close to independent -- real reordering value.
# ---------------------------------------------------------------------------

class _RankRecordingFIFO(BasePolicy):
    name = "fifo_rank_recording"

    def __init__(self, actual_output_by_id: Dict[int, int]):
        self._inner = make_policy("fifo")
        self._actual_output_by_id = actual_output_by_id
        self.first_admitted_ranks: List[int] = []

    def reset(self) -> None:
        self._inner.reset()
        self.first_admitted_ranks = []

    def select_action(self, state):
        queue = list(state.waiting_queue)
        if len(queue) >= 2:
            srtf_order = sorted(
                queue, key=lambda r: (self._actual_output_by_id[r.request_id], r.request_id)
            )
            rank_by_id = {r.request_id: i for i, r in enumerate(srtf_order)}
        else:
            rank_by_id = None
        action = self._inner.select_action(state)
        if rank_by_id is not None:
            admitted = sorted(action.all_admitted_ids())
            if admitted:
                self.first_admitted_ranks.append(rank_by_id[admitted[0]])
        return action


def compute_ordering_entropy(requests: List[Request], gpu_overrides: dict,
                              service_model_overrides: dict, drain_steps: int, seed: int) -> dict:
    sim_cfg = _build_sim_config(gpu_overrides, service_model_overrides, drain_steps)
    actual_by_id = {r.request_id: r.actual_output_tokens for r in requests}
    policy = _RankRecordingFIFO(actual_by_id)
    _run_policy(policy, requests, sim_cfg, seed)
    ranks = policy.first_admitted_ranks
    if not ranks:
        return {"ordering_entropy_bits": float("nan"), "n_ranked_decisions": 0, "max_entropy_bits": float("nan")}
    counts = np.bincount(ranks)
    probs = counts[counts > 0] / len(ranks)
    entropy = float(-np.sum(probs * np.log2(probs)))
    max_entropy = float(np.log2(len(counts))) if len(counts) > 1 else 0.0
    return {
        "ordering_entropy_bits": entropy,
        "n_ranked_decisions": len(ranks),
        "max_entropy_bits": max_entropy,
        "normalized_entropy": (entropy / max_entropy) if max_entropy > 0 else 0.0,
    }


def compute_headroom_score(metrics: dict, entropy: dict) -> float:
    """Composite, documented headroom score in [0, 1] (not a gate by
    itself -- see docs/audits/canonical_benchmark_suite_design_20260804.md
    for the justification of weights). Equal-weighted mean of four
    normalized signals, each clipped to [0, 1]:
      - anwg_gap normalized against a 0.10 (10 percentage point) reference
        ceiling (chosen as roughly the middle of this suite's observed
        range, 0.02-0.50 -- not a hard requirement, just a scoring scale)
      - queue_contention_fraction directly (already in [0, 1])
      - fifo_srtf_decision_disagreement_fraction normalized against a 0.05
        reference ceiling (5% disagreement is already substantial given
        the WildChat control's own 0.5%)
      - normalized_entropy directly (already in [0, 1])
    """
    def _clip01(x: float) -> float:
        if np.isnan(x):
            return 0.0
        return float(np.clip(x, 0.0, 1.0))

    anwg_component = _clip01(metrics["fifo_srtf_anwg_gap"] / 0.10)
    contention_component = _clip01(metrics["queue_contention_fraction"])
    disagreement_component = _clip01(metrics["fifo_srtf_decision_disagreement_fraction"] / 0.05)
    entropy_component = _clip01(entropy.get("normalized_entropy", 0.0))
    return float(np.mean([anwg_component, contention_component, disagreement_component, entropy_component]))


def validate_family(family: WorkloadFamily, seeds: List[int], drain_steps: int) -> dict:
    per_seed = []
    for seed in seeds:
        requests = generate_workload(family.workload, seed=seed)
        metrics = compute_headroom_metrics(requests, family.gpu, family.service_model, drain_steps, seed)
        entropy = compute_ordering_entropy(requests, family.gpu, family.service_model, drain_steps, seed)
        gate = evaluate_gate(metrics)
        score = compute_headroom_score(metrics, entropy)
        per_seed.append({"seed": seed, "metrics": metrics, "entropy": entropy, "gate": gate, "headroom_score": score})

    # Acceptance is decided on the MEAN across seeds (more robust than a
    # single seed) -- a family must pass the gate's 4 checks on average.
    mean_anwg_gap = float(np.mean([p["metrics"]["fifo_srtf_anwg_gap"] for p in per_seed]))
    mean_disagreement = float(np.mean([p["metrics"]["fifo_srtf_decision_disagreement_fraction"] for p in per_seed]))
    mean_contention = float(np.mean([p["metrics"]["queue_contention_fraction"] for p in per_seed]))
    all_tied_every_seed = all(p["metrics"]["all_four_policies_bit_identical_anwg"] for p in per_seed)
    mean_headroom_score = float(np.mean([p["headroom_score"] for p in per_seed]))

    accept = (
        mean_disagreement > 0
        and mean_anwg_gap >= GATE_MIN_ANWG_GAP
        and mean_contention >= GATE_MIN_QUEUE_CONTENTION_FRACTION
        and not all_tied_every_seed
    )

    return {
        "family": family.name,
        "target_phenomenon": family.target_phenomenon,
        "hypothesis": family.hypothesis,
        "expected_divergent_policies": family.expected_divergent_policies,
        "expected_winner": family.expected_winner,
        "per_seed": per_seed,
        "mean_fifo_srtf_anwg_gap": mean_anwg_gap,
        "mean_fifo_srtf_decision_disagreement_fraction": mean_disagreement,
        "mean_queue_contention_fraction": mean_contention,
        "mean_headroom_score": mean_headroom_score,
        "accepted": accept,
    }


# ---------------------------------------------------------------------------
# Foundational-heuristic comparison (only pre-existing deployable policies
# + the non-deployable oracle_srtf ceiling -- no learned selector, no
# contextual composition, no CC5).
# ---------------------------------------------------------------------------

def run_foundational_comparison(
    workloads: Dict[str, List[List[Request]]],  # name -> [requests_per_seed]
    gpu_by_workload: Dict[str, dict],
    service_model_by_workload: Dict[str, dict],
    seeds: List[int],
    drain_steps: int,
) -> dict:
    per_workload: Dict[str, dict] = {}
    for name, requests_per_seed in workloads.items():
        sim_cfg = _build_sim_config(gpu_by_workload.get(name, {}), service_model_by_workload.get(name, {}), drain_steps)
        anwg_by_policy_seed: Dict[str, Dict[int, float]] = {}
        for seed, requests in zip(seeds, requests_per_seed):
            for pname in FOUNDATIONAL_POLICIES:
                m = _run_policy(make_policy(pname), requests, sim_cfg, seed)
                anwg_by_policy_seed.setdefault(pname, {})[seed] = m.arrival_normalized_weighted_goodput
            m_oracle = _run_policy(build_oracle(requests), requests, sim_cfg, seed)
            anwg_by_policy_seed.setdefault(ORACLE_POLICY, {})[seed] = m_oracle.arrival_normalized_weighted_goodput

        means = {p: float(np.mean(list(by_seed.values()))) for p, by_seed in anwg_by_policy_seed.items()}
        ranking = sorted(means, key=lambda p: -means[p])
        oracle_mean = means[ORACLE_POLICY]
        regret = {p: oracle_mean - means[p] for p in FOUNDATIONAL_POLICIES}

        pairwise = {p: {"wins": 0, "ties": 0, "losses": 0} for p in FOUNDATIONAL_POLICIES + [ORACLE_POLICY]}
        for seed in seeds:
            vals = {p: anwg_by_policy_seed[p][seed] for p in anwg_by_policy_seed}
            policies = sorted(vals.keys())
            for i, pi in enumerate(policies):
                for pj in policies[i + 1:]:
                    if abs(vals[pi] - vals[pj]) <= 1e-9:
                        pairwise[pi]["ties"] += 1
                        pairwise[pj]["ties"] += 1
                    elif vals[pi] > vals[pj]:
                        pairwise[pi]["wins"] += 1
                        pairwise[pj]["losses"] += 1
                    else:
                        pairwise[pj]["wins"] += 1
                        pairwise[pi]["losses"] += 1

        unique_wins = {p: 0 for p in anwg_by_policy_seed}
        for seed in seeds:
            vals = {p: anwg_by_policy_seed[p][seed] for p in anwg_by_policy_seed}
            best = max(vals.values())
            top = [p for p, v in vals.items() if abs(v - best) <= 1e-9]
            if len(top) == 1:
                unique_wins[top[0]] += 1

        per_workload[name] = {
            "anwg_mean_by_policy": means,
            "ranking_best_to_worst": ranking,
            "regret_vs_oracle": regret,
            "pairwise_win_tie_loss": pairwise,
            "unique_wins_by_seed": unique_wins,
        }

    # Behavioral similarity matrix: pairwise Pearson correlation, across
    # workloads, of each policy's mean ANWG vector -- how similarly two
    # policies behave across the whole accepted suite (not per-workload).
    all_policies = FOUNDATIONAL_POLICIES + [ORACLE_POLICY]
    workload_names = sorted(per_workload.keys())
    policy_vectors = {
        p: np.array([per_workload[w]["anwg_mean_by_policy"][p] for w in workload_names])
        for p in all_policies
    }
    similarity_matrix = {}
    for pi in all_policies:
        similarity_matrix[pi] = {}
        for pj in all_policies:
            vi, vj = policy_vectors[pi], policy_vectors[pj]
            if np.std(vi) == 0 or np.std(vj) == 0:
                similarity_matrix[pi][pj] = float("nan")
            else:
                similarity_matrix[pi][pj] = float(np.corrcoef(vi, vj)[0, 1])

    return {
        "per_workload": per_workload,
        "behavioral_similarity_matrix_pearson": similarity_matrix,
        "workload_order": workload_names,
    }


# ---------------------------------------------------------------------------
# Diversity analysis: how different are the accepted workloads themselves
# (not the policies) -- feature-space distance + headroom-signal spread.
# ---------------------------------------------------------------------------

FEATURE_KEYS = [
    "fifo_srtf_anwg_gap", "fifo_srtf_decision_disagreement_fraction",
    "queue_contention_fraction", "service_time_cv", "deadline_slack_cv",
    "prompt_predicted_output_correlation",
]


def diversity_analysis(validations: List[dict]) -> dict:
    names = [v["family"] for v in validations]
    features = []
    for v in validations:
        mean_metrics = {
            k: float(np.mean([p["metrics"][k] for p in v["per_seed"]])) for k in FEATURE_KEYS
        }
        features.append([mean_metrics[k] for k in FEATURE_KEYS])
    features = np.nan_to_num(np.array(features), nan=0.0)

    # z-score normalize each feature dimension before computing distances,
    # so no single raw-scale feature (e.g. anwg_gap's 0-0.5 range vs a
    # correlation's -1..1 range) dominates the Euclidean distance.
    mu = features.mean(axis=0)
    sigma = features.std(axis=0)
    sigma[sigma == 0] = 1.0
    z = (features - mu) / sigma

    n = len(names)
    dist_matrix = {}
    for i in range(n):
        dist_matrix[names[i]] = {}
        for j in range(n):
            dist_matrix[names[i]][names[j]] = float(np.linalg.norm(z[i] - z[j]))

    headroom_scores = [v["mean_headroom_score"] for v in validations]
    return {
        "feature_keys": FEATURE_KEYS,
        "pairwise_feature_distance_zscore": dist_matrix,
        "headroom_score_by_family": dict(zip(names, headroom_scores)),
        "headroom_score_spread": {
            "min": float(np.min(headroom_scores)) if headroom_scores else float("nan"),
            "max": float(np.max(headroom_scores)) if headroom_scores else float("nan"),
            "std": float(np.std(headroom_scores)) if headroom_scores else float("nan"),
        },
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seeds", type=int, nargs="+", default=DEFAULT_SEEDS)
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--drain-steps", type=int, default=DEFAULT_DRAIN_STEPS)
    parser.add_argument("--dry-run", action="store_true", help="Print family specs only, generate nothing.")
    parser.add_argument("--compare", action="store_true", help="Also run the foundational-heuristic comparison.")
    parser.add_argument("--diversity", action="store_true", help="Also run the diversity analysis.")
    parser.add_argument("--wildchat-max-requests", type=int, default=None)
    args = parser.parse_args()

    families = _families()

    if args.dry_run:
        for fam in families:
            print(json.dumps({
                "name": fam.name,
                "target_phenomenon": fam.target_phenomenon,
                "hypothesis": fam.hypothesis,
                "expected_divergent_policies": fam.expected_divergent_policies,
                "expected_winner": fam.expected_winner,
                "workload": _workload_config_to_dict(fam.workload),
                "gpu": fam.gpu,
                "service_model": fam.service_model,
            }, indent=2, default=str))
        return

    os.makedirs(args.output_dir, exist_ok=True)
    t_start = time.perf_counter()

    validations = []
    accepted_requests: Dict[str, List[List[Request]]] = {}
    accepted_gpu: Dict[str, dict] = {}
    accepted_sm: Dict[str, dict] = {}

    for fam in families:
        requests_per_seed = []
        for seed in args.seeds:
            reqs = generate_and_write_dataset(fam, seed, args.output_dir)
            requests_per_seed.append(reqs)

        validation = validate_family(fam, args.seeds, args.drain_steps)
        validations.append(validation)

        fam_dir = os.path.join(args.output_dir, fam.name)
        manifest = {
            "name": fam.name,
            "suite_version": SUITE_VERSION,
            "target_phenomenon": fam.target_phenomenon,
            "hypothesis": fam.hypothesis,
            "expected_divergent_policies": fam.expected_divergent_policies,
            "expected_winner": fam.expected_winner,
            "workload_config": _workload_config_to_dict(fam.workload),
            "gpu": fam.gpu,
            "service_model": fam.service_model,
            "seeds": args.seeds,
            "dataset_sha256_by_seed": {
                str(seed): _sha256_of_obj([_request_to_dict(r) for r in sorted(reqs, key=lambda r: r.request_id)])
                for seed, reqs in zip(args.seeds, requests_per_seed)
            },
            "validation": validation,
        }
        with open(os.path.join(fam_dir, "manifest.json"), "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2, default=str)
        print(f"{'ACCEPTED' if validation['accepted'] else 'REJECTED'}: {fam.name}  "
              f"anwg_gap={validation['mean_fifo_srtf_anwg_gap']:.4f}  "
              f"headroom_score={validation['mean_headroom_score']:.3f}")

        if validation["accepted"]:
            accepted_requests[fam.name] = requests_per_seed
            accepted_gpu[fam.name] = fam.gpu
            accepted_sm[fam.name] = fam.service_model

    # WildChat control: real data, never regenerated/overwritten -- its
    # own headroom/validation numbers are the suite's documented negative
    # control (deliberately not held to the acceptance gate: it is
    # retained regardless, per the task's "WildChat must remain as the
    # negative/control benchmark").
    wildchat_requests_per_seed = [
        _load_wildchat_control_requests(seed, args.wildchat_max_requests) for seed in args.seeds
    ]
    wildchat_metrics = compute_headroom_metrics(
        wildchat_requests_per_seed[0], {}, {}, args.drain_steps, args.seeds[0]
    )
    wildchat_entropy = compute_ordering_entropy(
        wildchat_requests_per_seed[0], {}, {}, args.drain_steps, args.seeds[0]
    )
    accepted_requests["wildchat_control"] = wildchat_requests_per_seed
    accepted_gpu["wildchat_control"] = {}
    accepted_sm["wildchat_control"] = {}

    suite_manifest = {
        "suite_version": SUITE_VERSION,
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seeds": args.seeds,
        "families": [v["family"] for v in validations],
        "accepted": [v["family"] for v in validations if v["accepted"]],
        "rejected": [v["family"] for v in validations if not v["accepted"]],
        "control_workload": "wildchat_control (real WildChat-1M data, not regenerated -- see data/processed/wildchat/)",
        "control_workload_headroom": {"metrics": wildchat_metrics, "entropy": wildchat_entropy},
        "generation_runtime_s": time.perf_counter() - t_start,
    }

    comparison = None
    if args.compare:
        t_cmp = time.perf_counter()
        comparison = run_foundational_comparison(accepted_requests, accepted_gpu, accepted_sm, args.seeds, args.drain_steps)
        suite_manifest["foundational_comparison_runtime_s"] = time.perf_counter() - t_cmp
        with open(os.path.join(args.output_dir, "foundational_comparison.json"), "w", encoding="utf-8") as f:
            json.dump(comparison, f, indent=2, default=str)
        print(f"Wrote {os.path.join(args.output_dir, 'foundational_comparison.json')}")

    diversity = None
    if args.diversity:
        diversity = diversity_analysis(validations)
        with open(os.path.join(args.output_dir, "diversity_analysis.json"), "w", encoding="utf-8") as f:
            json.dump(diversity, f, indent=2, default=str)
        print(f"Wrote {os.path.join(args.output_dir, 'diversity_analysis.json')}")

    suite_manifest_path = os.path.join(args.output_dir, "suite_manifest.json")
    with open(suite_manifest_path, "w", encoding="utf-8") as f:
        json.dump(suite_manifest, f, indent=2, default=str)
    print(f"Wrote {suite_manifest_path}")

    print(f"\n=== Canonical benchmark suite: {len(validations)} synthetic families, "
          f"{len(suite_manifest['accepted'])} accepted, {len(suite_manifest['rejected'])} rejected "
          f"(+1 control) ===")
    print(f"Total generation+validation runtime: {suite_manifest['generation_runtime_s']:.1f}s")


if __name__ == "__main__":
    main()
