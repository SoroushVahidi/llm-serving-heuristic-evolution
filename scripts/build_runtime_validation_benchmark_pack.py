#!/usr/bin/env python3
"""Build the compact, canonical runtime-validation benchmark pack
(experiments/runtime_validation_benchmark_pack/) from already-completed
Wulver experiment artifacts already committed under
experiments/gpu_external_validity/. Submits no jobs, runs no GPU work, and
makes no network calls -- scenario fixtures are regenerated by calling the
exact same deterministic scenario-builder functions already used by the
completed jobs (scripts/run_sarathi_gpu_smoke_and_validation.py's
make_scenarios(), scripts/run_gpu_external_validity_audit.py's
build_mistral_match_scenarios()/build_xlong_stress_scenarios()), which is
pure local string/arithmetic work with no I/O.

Source jobs (all already completed, artifacts already committed):
  1111541 - vLLM Qwen2.5-7B baseline
  1111545 - vLLM Qwen2.5-7B aggressive stress
  1111572 - vLLM Qwen2.5-7B long-context (xlong)
  1111706 - real vLLM Mistral-7B matched comparison run
  1111723 - real Sarathi Mistral-7B fp16 runtime validation
  1111988 - repeated-trial Sarathi array (5 tasks)
  1111989 - repeated-trial vLLM array (5 tasks)
  1111990 - repeated-trial CPU postprocessing (statistics)

Usage:
    python scripts/build_runtime_validation_benchmark_pack.py
"""
from __future__ import annotations

import hashlib
import json
import statistics
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import run_sarathi_gpu_smoke_and_validation as sarathi_harness  # noqa: E402
import run_gpu_external_validity_audit as vllm_harness  # noqa: E402

GPU_DIR = ROOT / "experiments" / "gpu_external_validity"
OUT_DIR = ROOT / "experiments" / "runtime_validation_benchmark_pack"

# (sarathi scenario name, vllm scenario name, canonical short id)
SCENARIO_TRIPLES = [
    ("sarathi_long_prompt_moderate_output", "mistral_match_long_prompt_moderate_output", "long_prompt_moderate_output"),
    ("sarathi_active_decode_plus_arriving_prefill", "mistral_match_active_decode_plus_arriving_prefill", "active_decode_plus_arriving_prefill"),
    ("sarathi_prefill_heavy_burst", "mistral_match_prefill_heavy_burst", "prefill_heavy_burst"),
    ("sarathi_mixed_prompt_lengths", "mistral_match_mixed_prompt_lengths", "mixed_prompt_lengths"),
    ("sarathi_matched_vllm_kv_pressure", "mistral_match_kv_pressure", "kv_pressure"),
]

POSITIVE_TARGETS = {"active_decode_plus_arriving_prefill", "kv_pressure"}
NEGATIVE_CONTROLS = {"long_prompt_moderate_output", "prefill_heavy_burst", "mixed_prompt_lengths"}


def load_json(path: Path) -> Any:
    return json.loads(path.read_text())


def sha256_of_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# 1. Scenario fixtures
# ---------------------------------------------------------------------------

def build_scenario_fixtures() -> None:
    scenarios_dir = OUT_DIR / "scenarios"
    scenarios_dir.mkdir(parents=True, exist_ok=True)

    sarathi_scenarios = {s["name"]: s for s in sarathi_harness.make_scenarios()}
    vllm_scenarios = {s.name: s for s in vllm_harness.build_mistral_match_scenarios(ROOT)}

    for sarathi_name, vllm_name, short_id in SCENARIO_TRIPLES:
        s_scenario = sarathi_scenarios[sarathi_name]
        v_scenario = vllm_scenarios[vllm_name]

        requests = []
        for sreq, vreq in zip(s_scenario["requests"], v_scenario.requests):
            assert sreq.prompt_text == vreq.prompt_text, f"prompt mismatch in {short_id} request {sreq.idx}"
            requests.append({
                "request_id": sreq.idx,
                "arrival_time_s": sreq.arrival_offset_s,
                "prompt_bucket": sreq.prompt_bucket,
                "target_output_tokens": sreq.target_output_tokens,
                "intended_prompt_tokens_approx": vreq.intended_prompt_tokens,
                "prompt_char_length": len(sreq.prompt_text),
                "prompt_sha256": hashlib.sha256(sreq.prompt_text.encode()).hexdigest(),
            })
        # arrival_time_s ordering is the request generation order; also
        # explicitly record arrival order separately in case a consumer
        # wants to iterate by arrival rather than request_id.
        arrival_order = [r["request_id"] for r in sorted(requests, key=lambda r: (r["arrival_time_s"], r["request_id"]))]

        fixture = {
            "canonical_scenario_id": short_id,
            "category": short_id,
            "positive_target": short_id in POSITIVE_TARGETS,
            "negative_control": short_id in NEGATIVE_CONTROLS,
            "sarathi_harness_name": sarathi_name,
            "vllm_harness_name": vllm_name,
            "source_functions": [
                "scripts/run_sarathi_gpu_smoke_and_validation.py:make_scenarios",
                "scripts/run_gpu_external_validity_audit.py:build_mistral_match_scenarios",
            ],
            "prompt_seed": 20260719,
            "request_count": len(requests),
            "max_client_concurrency": v_scenario.max_client_concurrency,
            "arrival_order_by_request_id": arrival_order,
            "requests": requests,
            "note": (
                "Full prompt text is deliberately omitted (compact fixture); "
                "prompt_sha256 lets a consumer verify regenerated prompt text "
                "matches exactly. Regenerate full prompts by calling "
                "llmserveopt.real_llm.calibration_common.build_length_targeted_prompt"
                "(prompt_bucket, target_output_tokens, seed=20260719, variant_index=...) "
                "-- variant_index is not itself stored here since it is an internal "
                "implementation detail of the two source functions above, not part "
                "of the observable scenario contract; the sha256 is the portable "
                "verification mechanism."
            ),
        }
        (scenarios_dir / f"{short_id}.json").write_text(json.dumps(fixture, indent=2, sort_keys=False) + "\n")

    print(f"wrote {len(SCENARIO_TRIPLES)} scenario fixtures to {scenarios_dir}")


# ---------------------------------------------------------------------------
# 2. Real-hardware target summaries (from repeated-trial results)
# ---------------------------------------------------------------------------

def build_hardware_targets() -> None:
    targets_dir = OUT_DIR / "hardware_targets"
    targets_dir.mkdir(parents=True, exist_ok=True)

    repeated_dir = GPU_DIR / "sarathi_vllm_repeated_trials"
    summary_rows = load_json(repeated_dir / "repeated_trials_summary.json")
    bootstrap = load_json(repeated_dir / "bootstrap_comparison.json")

    by_scenario_metric: dict[tuple[str, str], dict] = {(r["scenario"], r["metric"]): r for r in summary_rows}

    for _sarathi_name, vllm_name, short_id in SCENARIO_TRIPLES:
        metrics: dict[str, Any] = {}
        for metric in ("ttft_s", "tpot_s", "e2e_s"):
            row = by_scenario_metric.get((vllm_name, metric))
            if row is None:
                continue
            metrics[metric] = {
                "sarathi": {"n": row["sarathi_n"], "mean": row["sarathi_mean"], "median": row["sarathi_median"],
                            "stdev": row["sarathi_stdev"], "p50": row["sarathi_p50"], "p95": row["sarathi_p95"]},
                "vllm": {"n": row["vllm_n"], "mean": row["vllm_mean"], "median": row["vllm_median"],
                         "stdev": row["vllm_stdev"], "p50": row["vllm_p50"], "p95": row["vllm_p95"]},
                "sarathi_over_vllm_ratio_of_means": row.get("sarathi_over_vllm_ratio_of_means"),
            }
        boot = bootstrap.get(vllm_name, {})
        e2e_boot = boot.get("e2e_paired_bootstrap", {})
        n_trials = boot.get("n_trials", 0)
        sarathi_wins = boot.get("sarathi_e2e_wins", 0)
        winner_identity = "sarathi" if sarathi_wins > n_trials - sarathi_wins else ("vllm" if n_trials else "n/a")

        record = {
            "canonical_scenario_id": short_id,
            "metrics": metrics,
            "winner_identity_e2e": winner_identity,
            "winner_frequency_e2e": f"{sarathi_wins}/{n_trials}" if winner_identity == "sarathi" else f"{n_trials - sarathi_wins}/{n_trials}",
            "sarathi_e2e_win_count": sarathi_wins,
            "vllm_e2e_win_count": n_trials - sarathi_wins,
            "n_trials": n_trials,
            "e2e_bootstrap_95ci_vllm_minus_sarathi": [e2e_boot.get("ci95_lo"), e2e_boot.get("ci95_hi")],
            "e2e_mean_diff_vllm_minus_sarathi": e2e_boot.get("mean_diff_vllm_minus_sarathi"),
            "robustness_classification": boot.get("robustness"),
            "positive_target": short_id in POSITIVE_TARGETS,
            "negative_control": short_id in NEGATIVE_CONTROLS,
            "provenance": {
                "sarathi_array_job": 1111988,
                "vllm_array_job": 1111989,
                "postprocess_job": 1111990,
                "single_run_sarathi_job": 1111723,
                "single_run_vllm_job": 1111706,
            },
        }
        (targets_dir / f"{short_id}.json").write_text(json.dumps(record, indent=2, default=str) + "\n")

    print(f"wrote {len(SCENARIO_TRIPLES)} hardware target summaries to {targets_dir}")


