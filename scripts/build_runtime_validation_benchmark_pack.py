def build_kv_progression_fixture() -> None:
    kv_dir = OUT_DIR / "kv_progression"
    kv_dir.mkdir(parents=True, exist_ok=True)

    jobs = {
        1111541: "vllm_qwen7b_a100_baseline_1111541",
        1111545: "vllm_qwen7b_a100_aggressive_1111545",
        1111572: "vllm_qwen7b_a100_xlong_1111572",
    }
    # KV pool token counts recorded from each job's server.log at run time
    # (server.log itself is not committed -- raw log, see repo policy).
    # Reproduced here from the already-committed
    # docs/wulver_vllm_kv_pressure_results.md, not re-derived.
    kv_pool_tokens = {1111541: 925824, 1111545: 226960, 1111572: 237184}
    headroom_ratio = {1111541: 45.1, 1111545: 7.16, 1111572: 1.195}

    entries = []
    for job_id, dirname in jobs.items():
        summary = load_json(GPU_DIR / dirname / "summary.json")
        env = load_json(GPU_DIR / dirname / "environment.json")
        entries.append({
            "job_id": job_id,
            "server_command": env.get("server_command"),
            "max_observed_kv_cache_usage": summary["max_observed_kv_cache_usage"],
            "max_observed_vllm_running": summary["max_observed_vllm_running"],
            "num_requests": summary["num_requests"],
            "num_success": summary["num_success"],
            "preemption_events": summary["preemption_events"],
            "kv_pool_tokens": kv_pool_tokens[job_id],
            "headroom_ratio_1_over_max_kv_usage": headroom_ratio[job_id],
        })

    fixture = {
        "canonical_id": "kv_progression",
        "purpose": (
            "Structural KV-pressure/preemption regression target: peak KV utilization, running/waiting "
            "counts, and preemption events should stay directionally consistent (not exact-timing "
            "consistent) with this progression for the same model/GPU/config triple. Preemption was 0 "
            "in all three jobs despite headroom dropping from ~45x to ~1.2x -- treat this as a structural "
            "fact to check for (queueing-over-eviction admission-control behavior), not a timing target."
        ),
        "model": "Qwen/Qwen2.5-7B-Instruct",
        "gpu": "NVIDIA A100-SXM4-80GB",
        "kv_pool_tokens_provenance": (
            "Recorded from each job's server.log (vLLM's own 'GPU KV cache size' startup log line) at "
            "run time; server.log is not committed (raw log). Reproduced here from the already-committed "
            "docs/wulver_vllm_kv_pressure_results.md, section reporting these exact figures."
        ),
        "jobs": entries,
    }
    (kv_dir / "kv_progression.json").write_text(json.dumps(fixture, indent=2, default=str) + "\n")
    print(f"wrote KV progression fixture to {kv_dir}")


