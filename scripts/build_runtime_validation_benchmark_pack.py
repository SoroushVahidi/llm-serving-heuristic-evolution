def build_simulator_baseline_results() -> None:
    sim_dir = OUT_DIR / "simulator_baseline_results"
    sim_dir.mkdir(parents=True, exist_ok=True)

    vllm_1111706 = load_json(GPU_DIR / "vllm_mistral7b_a100_match_1111706" / "scenario_results.json")
    by_name = {r["scenario"]["name"]: r for r in vllm_1111706}

    hw_targets_dir = OUT_DIR / "hardware_targets"

    for _sarathi_name, vllm_name, short_id in SCENARIO_TRIPLES:
        entry = by_name[vllm_name]
        vf = entry["simulator_summary"]["vllm_faithful"]
        sf = entry["simulator_summary"]["sarathi_faithful"]

        vf_e2e, sf_e2e = vf.get("mean_latency_s"), sf.get("mean_latency_s")
        if vf_e2e is not None and sf_e2e is not None:
            sim_winner = "vllm" if vf_e2e < sf_e2e else ("sarathi" if sf_e2e < vf_e2e else "tie")
        else:
            sim_winner = "n/a (vllm_faithful dropped all requests)"

        hw_target = load_json(hw_targets_dir / f"{short_id}.json")
        hw_winner = hw_target["winner_identity_e2e"]
        matches_hardware = (sim_winner == hw_winner) if sim_winner in ("vllm", "sarathi") else False

        known_mismatch_reason = None
        if not matches_hardware and short_id == "active_decode_plus_arriving_prefill":
            known_mismatch_reason = (
                "Documented in docs/wulver_vllm_kv_pressure_results.md (session 3): the simulator does "
                "not model the specific dynamic of an already-decoding sequence competing with a newly "
                "arriving long-prefill request for the next scheduling slot with enough fidelity to "
                "reproduce which system actually wins this regime. Confirmed a stable (ROBUST, 5/5) real "
                "effect by docs/wulver_sarathi_vllm_repeated_validation.md, not single-run noise."
            )
        elif not matches_hardware and short_id == "kv_pressure":
            known_mismatch_reason = (
                "Not specifically root-caused at the scheduler-algorithm level (unlike the "
                "active_decode_plus_arriving_prefill mismatch). Confirmed a stable (ROBUST, 5/5) real "
                "effect by docs/wulver_sarathi_vllm_repeated_validation.md."
            )

        record = {
            "canonical_scenario_id": short_id,
            "vllm_faithful": {"mean_ttft_s": vf.get("mean_ttft_s"), "mean_e2e_s": vf_e2e,
                               "completion_fraction": vf.get("completion_fraction")},
            "sarathi_faithful": {"mean_ttft_s": sf.get("mean_ttft_s"), "mean_e2e_s": sf_e2e,
                                   "completion_fraction": sf.get("completion_fraction")},
            "simulator_e2e_winner": sim_winner,
            "hardware_e2e_winner_robust": hw_winner,
            "simulator_matches_hardware": matches_hardware,
            "known_mismatch_reason": known_mismatch_reason,
            "source_job_for_simulator_numbers": 1111706,
            "note": "Simulator numbers were computed inline by job 1111706 (run_simulator_scenario()); not rerun for this pack.",
        }
        (sim_dir / f"{short_id}.json").write_text(json.dumps(record, indent=2, default=str) + "\n")

    print(f"wrote {len(SCENARIO_TRIPLES)} simulator baseline results to {sim_dir}")


