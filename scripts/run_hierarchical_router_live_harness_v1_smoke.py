#!/usr/bin/env python3
"""Hierarchical Regime Router v1 -- LIVE closed-loop harness smoke +
methodology comparison.

TRAIN/VAL/SYNTHETIC-MICROCASE ONLY. Never reads a `split == "test"` row,
never computes a scientific TEST verdict, never modifies the frozen
router/Stage-1/Stage-2/gate artifacts. See
docs/audits/hierarchical_router_live_harness_validation_v1_20260818.md for
the full writeup this script's output feeds.

What this script does, in order:
  1. Fits Stage-1 (frozen `Stage1Router`) on real TRAIN telemetry and
     Stage-2 (frozen `Stage2Selector` x3) on real TRAIN scenario rows --
     identical fitting code to `run_hierarchical_regime_router_v1_smoke.py`,
     not retrained differently.
  2. Forced-parent equivalence: for each of the six native policies, runs
     a small synthetic fixture scenario both directly (`Simulator` + that
     policy) and through the live harness in forced-expert mode; asserts
     ANWG matches.
  3. Causal-switch microcase: runs the frozen B+C blended microcase through
     the live harness (real routing) and through a fallback-only forced
     run from the SAME initial scenario; shows the two trajectories are
     identical until the first real regime switch and diverge after it.
  4. TRAIN/VAL live smoke: runs the live harness (real routing, no forcing)
     across a handful of real TRAIN/VAL MF-PSD scenarios (Family A and
     Family B, looked up by canonical_scenario_id so their EXACT frozen
     Stage-2 feature rows are used) plus the B+C blended microcase (for
     Regime-C reachability, since Family C native scenarios cannot be
     regenerated byte-exact -- see SS11 of the validation doc / this
     script's own docstring note below). Confirms: no crash, no NaN/Inf,
     dwell violations == 0, trajectory logs complete, all three regime
     paths reached across the fixture set.
  5. Methodology comparison: for the SAME real TRAIN/VAL scenarios, computes
     (a) the OLD offline scenario-level majority-vote dispatch (imported
     ONLY here, in the comparison script -- never inside the live harness
     module itself, see that module's own regression-guarded S5) and (b)
     the NEW live per-step ANWG, and reports where/how they diverge. This
     is a methodology diagnostic only -- nothing here tunes anything.

NOTE on Family C: `unified_utility_matrix.py` already documents that
Family C / KV v2 scenarios cannot be regenerated byte-exact from the
current template code (`kv_v2_reproducibility_forensic_20260817.md`).
This script therefore never attempts to re-run a real Family-C MF-PSD
scenario through the simulator; Regime-C (KV_MEMORY_PRESSURE) reachability
is instead demonstrated via the frozen B+C blended microcase, which the
prior TEST audit already confirmed empirically activates KV pressure. This
is a pre-existing, separately-documented limitation, not something this
task fixes or works around by touching Family C's reconstruction path.
"""
