def _git_sha() -> Optional[str]:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except Exception:
        return None


def _git_dirty() -> Optional[bool]:
    try:
        out = subprocess.check_output(
            ["git", "status", "--porcelain"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        )
        return bool(out.strip())
    except Exception:
        return None


def _sha256_file(path: Path) -> Optional[str]:
    try:
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        return h.hexdigest()
    except Exception:
        return None


def _load_runner_module(script_relpath: str):
    """Import a frozen runner script (unmodified) as a module, purely to
    reuse its scenario-construction function. __main__ side effects never
    run because we only call specific functions, never the module as a
    script."""
    path = ROOT / script_relpath
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def regenerate_family_a_scenarios(config_path: Optional[Path] = None) -> List[Any]:
    config_path = config_path or (ROOT / "configs/policy_separation_fairness_starvation_pilot_v2.yaml")
    mod = _load_runner_module("scripts/run_policy_separation_fairness_starvation_pilot_v2.py")
    cfg = yaml.safe_load(open(config_path))
    return mod.build_scenarios_from_config(cfg, allow_synthetic_tokens=False)


def regenerate_family_b_scenarios(config_path: Optional[Path] = None) -> List[Any]:
    config_path = config_path or (ROOT / "configs/policy_separation_prefill_decode_pilot_v2.yaml")
    mod = _load_runner_module("scripts/run_policy_separation_prefill_decode_pilot_v2.py")
    cfg = yaml.safe_load(open(config_path))
    return mod.build_scenarios_from_config(
        cfg, allow_synthetic_tokens=False, datasets_root=ROOT / ".local_data"
    )


def _build_policy(canonical_policy_id: str):
    """Return (policy_instance, service_model_kwargs_override: dict)."""
    if canonical_policy_id == "estimated_service_time_first":
        return EstimatedServiceTimeFirstPolicy(), {}
    if canonical_policy_id == "weighted_fair_share":
        return WeightedFairSharePolicy(), {}
    if canonical_policy_id == "least_laxity_first":
        return LeastLaxityFirstPolicy(), {}
    if canonical_policy_id == "kv_constrained_online":
        return KVConstrainedOnlinePolicy(), {}
    if canonical_policy_id in ("full_prefill", "chunked_prefill_small"):
        variants = make_prefill_decode_variants_v2(chunk_small=64)
        policy, variant_kwargs = variants[canonical_policy_id]
        return policy, dict(variant_kwargs)
    raise KeyError(f"Unknown canonical_policy_id {canonical_policy_id!r}")


def run_cell(scenario: Any, canonical_policy_id: str, mechanism_family: str) -> Dict[str, Any]:
    """Evaluate one (scenario, anchor policy) cell. Never raises: failures
    are captured in the returned row's status/error fields."""
    canonical_scenario_id = f"{mechanism_family}::{scenario.scenario_id}"
    native_family = NATIVE_FAMILY_OF_POLICY[canonical_policy_id]
    degenerate = canonical_policy_id in DEGENERATE_MECHANISM_POLICIES and mechanism_family != native_family
    row: Dict[str, Any] = {
        "uum_row_id": f"{canonical_scenario_id}::{canonical_policy_id}",
        "canonical_scenario_id": canonical_scenario_id,
        "source_scenario_id": scenario.scenario_id,
        "mechanism_family": mechanism_family,
        "canonical_policy_id": canonical_policy_id,
        "native_family_of_policy": native_family,
        "cell_source": "STEP2_CROSS_FAMILY_EVALUATION",
        "degenerate_mechanism": degenerate,
        "degenerate_reason": DEGENERATE_REASON if degenerate else "",
        "builder_version": BUILDER_VERSION,
    }
    try:
        policy, sm_override = _build_policy(canonical_policy_id)
        merged_sm = dict(scenario.service_model_kwargs)
        merged_sm.update(sm_override)
        sim = Simulator(SimulatorConfig(
            gpu_configs=list(scenario.gpu_configs),
            service_model=ServiceModel(**merged_sm),
        ))
        sim.load_trace(list(scenario.requests))
        metrics = sim.run(policy, workload_tag=scenario.scenario_id, seed=scenario.seed)
        completed = list(sim._completed)  # noqa: SLF001
        n_req = len(scenario.requests)
        n_violated = sum(1 for c in completed if c.slo_violated)
        unweighted = (len(completed) - n_violated) / max(1, n_req)
        row.update({
            "status": "success",
            "primary_utility_anwg": float(metrics.arrival_normalized_weighted_goodput),
            "secondary_completion_fraction": float(metrics.completion_fraction),
            "secondary_unweighted_slo_success_rate": float(unweighted),
            "error": "",
        })
    except Exception as e:  # noqa: BLE001
        row.update({
            "status": "failed",
            "primary_utility_anwg": float("nan"),
            "secondary_completion_fraction": float("nan"),
            "secondary_unweighted_slo_success_rate": float("nan"),
            "error": f"{type(e).__name__}: {e}\n{traceback.format_exc()}",
        })
    return row


def unsupported_row(canonical_scenario_id: str, source_scenario_id: str, mechanism_family: str, canonical_policy_id: str) -> Dict[str, Any]:
    native_family = NATIVE_FAMILY_OF_POLICY[canonical_policy_id]
    return {
        "uum_row_id": f"{canonical_scenario_id}::{canonical_policy_id}",
        "canonical_scenario_id": canonical_scenario_id,
        "source_scenario_id": source_scenario_id,
        "mechanism_family": mechanism_family,
        "canonical_policy_id": canonical_policy_id,
        "native_family_of_policy": native_family,
        "cell_source": "STEP2_CROSS_FAMILY_EVALUATION",
        "degenerate_mechanism": False,
        "degenerate_reason": "",
        "status": "unsupported_scenario_reconstruction",
        "primary_utility_anwg": float("nan"),
        "secondary_completion_fraction": float("nan"),
        "secondary_unweighted_slo_success_rate": float("nan"),
        "error": UNSUPPORTED_REASON,
        "builder_version": BUILDER_VERSION,
    }


def expected_new_cell_tasks() -> List[Dict[str, str]]:
    """The exact, frozen list of (mechanism_family, canonical_policy_id)
    pairs that require NEW cross-family evaluation, per the preregistered
    executability audit (design doc S2). Excludes native pairs and every
    pair targeting a BLOCKED_TARGET_FAMILIES family."""
    tasks = []
    for family in ALL_FAMILIES:
        for policy_id in CANONICAL_ANCHOR_IDS:
            if NATIVE_FAMILY_OF_POLICY[policy_id] == family:
                continue  # native, already in MF-PSD v1
            tasks.append({"mechanism_family": family, "canonical_policy_id": policy_id})
    return tasks
