"""Scenario schema for the Policy Separation Dataset v1.

See docs/design/POLICY_SEPARATION_DATASET_V1.md sections 6-7. Extends the
existing `Request`/`GPUConfig` dataclasses (core.types) with scenario-level
provenance, a falsifiable qualitative hypothesis, stress/control pairing,
and inert module-intervention hooks reserved for a later phase.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Dict, Optional, Tuple

from ..core.types import GPUConfig, Request

#: Valid values for PolicySeparationScenario.stress_control_relationship.
STRESS_CONTROL_ROLES = (None, "stress", "control")


@dataclass(frozen=True)
class PolicySeparationScenario:
    """One deterministic, hypothesis-tagged scenario.

    `requests`/`gpu_configs` are the actual simulator inputs; `params`
    records the exact keyword arguments the template function was called
    with, so the scenario can be regenerated byte-for-byte from
    (template function, params, seed) without serializing raw requests.
    """

    scenario_id: str
    family: str
    template_name: str
    generator_version: str
    seed: int
    params: Dict[str, Any]

    requests: Tuple[Request, ...]
    gpu_configs: Tuple[GPUConfig, ...]
    service_model_kwargs: Dict[str, Any] = field(default_factory=dict)

    target_policy_family: str = ""
    target_mechanism: str = ""
    expected_qualitative_hypothesis: str = ""
    stress_control_relationship: Optional[str] = None

    pair_id: Optional[str] = None
    changed_parameters: Tuple[str, ...] = ()

    # Module-intervention hooks (Phase 5, not exercised in Phase 1 — see
    # docs/design/POLICY_SEPARATION_DATASET_V1.md section 7). Always None
    # in every scenario produced by this phase's templates/perturbations.
    target_module: Optional[str] = None
    module_enabled: Optional[bool] = None
    intervention_parent_policy: Optional[str] = None
    intervention_pair_id: Optional[str] = None
    expected_module_effect: Optional[str] = None

    def __post_init__(self) -> None:
        if self.stress_control_relationship not in STRESS_CONTROL_ROLES:
            raise ValueError(
                f"stress_control_relationship must be one of {STRESS_CONTROL_ROLES}, "
                f"got {self.stress_control_relationship!r}"
            )
        if self.pair_id is not None and not self.changed_parameters:
            raise ValueError(
                f"scenario {self.scenario_id!r} has pair_id set but no "
                "changed_parameters — every paired scenario must record what "
                "differs from its counterpart (see design doc section 8)"
            )
        if not self.requests:
            raise ValueError(f"scenario {self.scenario_id!r} has no requests")
        if not self.gpu_configs:
            raise ValueError(f"scenario {self.scenario_id!r} has no gpu_configs")

    def to_manifest_dict(self) -> Dict[str, Any]:
        """JSON-serializable summary: no raw Request/GPUConfig payload
        (regenerable deterministically from `params` + `seed`), matching
        the repo's existing ScenarioIdentifiers convention of not
        persisting raw per-request data in the scenario manifest."""
        return {
            "scenario_id": self.scenario_id,
            "family": self.family,
            "template_name": self.template_name,
            "generator_version": self.generator_version,
            "seed": self.seed,
            "params": self.params,
            "num_requests": len(self.requests),
            "num_gpus": len(self.gpu_configs),
            "service_model_kwargs": self.service_model_kwargs,
            "target_policy_family": self.target_policy_family,
            "target_mechanism": self.target_mechanism,
            "expected_qualitative_hypothesis": self.expected_qualitative_hypothesis,
            "stress_control_relationship": self.stress_control_relationship,
            "pair_id": self.pair_id,
            "changed_parameters": list(self.changed_parameters),
            "target_module": self.target_module,
            "module_enabled": self.module_enabled,
            "intervention_parent_policy": self.intervention_parent_policy,
            "intervention_pair_id": self.intervention_pair_id,
            "expected_module_effect": self.expected_module_effect,
        }

    def gpu_configs_as_dicts(self) -> Tuple[Dict[str, Any], ...]:
        return tuple(asdict(g) for g in self.gpu_configs)
